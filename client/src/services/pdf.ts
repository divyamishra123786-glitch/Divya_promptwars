import jsPDF from 'jspdf';
import html2canvas from 'html2canvas';
import type { SavedAnalysis } from '../types';

export async function exportAnalysisPDF(analysis: SavedAnalysis): Promise<void> {
  const element = document.getElementById('analysis-content');

  if (!element) {
    // Fallback: generate text PDF
    const pdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
    generateTextPDF(pdf, analysis);
    pdf.save(`blindspot-analysis-${analysis.id.slice(0, 8)}.pdf`);
    return;
  }

  try {
    const canvas = await html2canvas(element, {
      backgroundColor: '#101214',
      scale: 1.5,
      useCORS: true,
      logging: false,
    });

    const imgData = canvas.toDataURL('image/jpeg', 0.85);
    const pdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
    const pageWidth = 210;
    const pageHeight = 297;
    const margin = 10;
    const contentWidth = pageWidth - margin * 2;
    const imgHeight = (canvas.height * contentWidth) / canvas.width;

    let yOffset = 0;
    let pageCount = 0;

    while (yOffset < imgHeight) {
      if (pageCount > 0) pdf.addPage();

      // Add branded header
      pdf.setFillColor(16, 18, 20);
      pdf.rect(0, 0, pageWidth, pageHeight, 'F');

      pdf.addImage(
        imgData,
        'JPEG',
        margin,
        margin - yOffset + (pageCount > 0 ? 0 : 5),
        contentWidth,
        imgHeight,
      );

      yOffset += pageHeight - margin * 2;
      pageCount++;
    }

    // Add footer
    for (let i = 1; i <= pdf.getNumberOfPages(); i++) {
      pdf.setPage(i);
      pdf.setFontSize(8);
      pdf.setTextColor(147, 153, 156);
      pdf.text('BlindSpot AI — See Beyond What You See. | Generated by AI — not professional advice.', margin, pageHeight - 5);
      pdf.text(`Page ${i} of ${pdf.getNumberOfPages()}`, pageWidth - margin - 20, pageHeight - 5);
    }

    pdf.save(`blindspot-${analysis.title.slice(0, 30).replace(/\s+/g, '-').toLowerCase()}.pdf`);
  } catch {
    // Fallback to text PDF
    const pdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
    generateTextPDF(pdf, analysis);
    pdf.save(`blindspot-analysis-${analysis.id.slice(0, 8)}.pdf`);
  }
}

function generateTextPDF(pdf: jsPDF, analysis: SavedAnalysis): void {
  const { result, title, createdAt } = analysis;
  const pageWidth = 210;
  const margin = 20;
  const maxWidth = pageWidth - margin * 2;
  let y = 25;

  const addLine = (text: string, fontSize = 11, bold = false, color = [245, 241, 235] as [number, number, number]) => {
    if (y > 270) {
      pdf.addPage();
      pdf.setFillColor(16, 18, 20);
      pdf.rect(0, 0, 210, 297, 'F');
      y = 25;
    }
    pdf.setFontSize(fontSize);
    pdf.setFont('helvetica', bold ? 'bold' : 'normal');
    pdf.setTextColor(...color);
    const lines = pdf.splitTextToSize(text, maxWidth);
    pdf.text(lines, margin, y);
    y += (lines.length * fontSize * 0.5) + 3;
  };

  // Background
  pdf.setFillColor(16, 18, 20);
  pdf.rect(0, 0, 210, 297, 'F');

  // Header
  pdf.setFillColor(34, 39, 42);
  pdf.rect(0, 0, 210, 18, 'F');
  pdf.setFontSize(12);
  pdf.setFont('helvetica', 'bold');
  pdf.setTextColor(242, 163, 109);
  pdf.text('BLINDSPOT AI', margin, 12);
  pdf.setFontSize(8);
  pdf.setFont('helvetica', 'normal');
  pdf.setTextColor(147, 153, 156);
  pdf.text('See Beyond What You See.', 80, 12);

  y = 28;

  addLine(title, 18, true, [242, 163, 109]);
  addLine(`Analyzed: ${new Date(createdAt).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}`, 9, false, [147, 153, 156]);
  addLine(`Mode: ${result.mode === 'demo' ? 'DEMO MODE — not real AI output' : 'Live AI Analysis'}`, 9, false, [147, 153, 156]);
  y += 4;

  addLine('EXECUTIVE SUMMARY', 10, true, [93, 99, 156]);
  addLine(result.executiveSummary, 11);
  y += 4;

  addLine('BLIND SPOTS', 10, true, [93, 99, 156]);
  result.blindSpots.forEach((bs, i) => {
    addLine(`${i + 1}. ${bs.title} [${bs.severity}]`, 11, true);
    addLine(bs.whatWasNoticed, 10);
    addLine(`Why it matters: ${bs.whyItMatters}`, 10);
    addLine(`Investigate: ${bs.whatToInvestigate}`, 10, false, [165, 181, 161]);
    y += 2;
  });

  addLine('CRITICAL QUESTIONS', 10, true, [93, 99, 156]);
  result.criticalQuestions.forEach((q, i) => {
    addLine(`${i + 1}. ${q}`, 10);
  });

  // Footer on all pages
  for (let i = 1; i <= pdf.getNumberOfPages(); i++) {
    pdf.setPage(i);
    pdf.setFontSize(7);
    pdf.setTextColor(93, 99, 156);
    pdf.text('BlindSpot AI — AI-estimated insights, not statistical analysis. Not professional advice.', margin, 293);
  }
}
